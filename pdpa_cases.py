def get_cases_for_obligation(obligation_name: str) -> list:
    """Returns list of real PDPC enforcement cases relevant to a given PDPA obligation."""
    for key in PDPA_CASES:
        if obligation_name.lower() in key.lower() or key.lower() in obligation_name.lower():
            return PDPA_CASES[key]
    return []


def format_cases_for_report(cases: list) -> list:
    """Formats cases into report-ready dicts with top 3 most relevant."""
    return [
        {
            "case_name": c["organisation"],
            "citation": c["citation"],
            "year": c["year"],
            "penalty_imposed": c["penalty"],
            "breach_type": c["headline_breach"],
            "summary": c["summary"]
        }
        for c in cases[:3]
    ]
